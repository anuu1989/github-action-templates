#!/usr/bin/env bash
# Scaffold a ready-to-run pipeline into the current repository.
#
#   curl -sSfL https://raw.githubusercontent.com/anuu1989/github-action-templates/v1/scripts/init-pipeline.sh | bash
#   curl -sSfL .../init-pipeline.sh | bash -s -- --type terraform --dir infra
#   curl -sSfL .../init-pipeline.sh | bash -s -- --type app --deploy ecs --registry ecr
#
# Options:
#   --type app|terraform|security   (default: auto-detect)
#   --deploy none|ecs|eks-helm      (app only, default none)
#   --registry ghcr|ecr             (app only, default ghcr)
#   --dir <path>                    (terraform working directory, default: auto-detect)
#   --ref <ref>                     (template version, default v1)
#   --force                         overwrite existing files
set -euo pipefail

TYPE="" DEPLOY=none REGISTRY=ghcr DIR="" REF=v1 FORCE=false
while [ $# -gt 0 ]; do
  case "$1" in
    --type) TYPE=$2; shift 2 ;;
    --deploy) DEPLOY=$2; shift 2 ;;
    --registry) REGISTRY=$2; shift 2 ;;
    --dir) DIR=$2; shift 2 ;;
    --ref) REF=$2; shift 2 ;;
    --force) FORCE=true; shift ;;
    -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

git rev-parse --show-toplevel >/dev/null 2>&1 || { echo "Run this inside a git repository" >&2; exit 1; }
cd "$(git rev-parse --show-toplevel)"
REPO_NAME=$(basename "$PWD")
BRANCH=$(git symbolic-ref --short refs/remotes/origin/HEAD 2>/dev/null | sed 's#^origin/##' || true)
BRANCH=${BRANCH:-main}
TPL="anuu1989/github-action-templates/.github/workflows"

if [ -z "$TYPE" ]; then
  is_app=false
  for marker in pom.xml 'build.gradle*' package.json pyproject.toml requirements.txt setup.py go.mod '*.sln' '*.csproj'; do
    compgen -G "$marker" >/dev/null && is_app=true && break
  done
  if [ "$is_app" = true ]; then TYPE=app
  elif [ -n "$(find . -maxdepth 3 -name '*.tf' -not -path '*/.terraform/*' -print -quit)" ]; then TYPE=terraform
  else TYPE=security; fi
  echo "Detected project type: $TYPE"
fi
if [ "$TYPE" = terraform ] && [ -z "$DIR" ]; then
  tf=$(find . -maxdepth 3 -name '*.tf' -not -path '*/.terraform/*' -not -path '*/modules/*' -print -quit)
  DIR=$(dirname "${tf:-./infra/x}"); DIR=${DIR#./}
fi

mkdir -p .github/workflows
write() { # path
  if [ -e "$1" ] && [ "$FORCE" != true ]; then echo "skip   $1 (exists, use --force)"; cat > /dev/null; return; fi
  cat > "$1"; echo "wrote  $1"
}

case "$TYPE" in
app)
  PERMS="      contents: read
      packages: write
      id-token: write"
  DEPLOY_BLOCK=""
  if [ "$DEPLOY" != none ]; then
    DEPLOY_BLOCK="      deploy-target: $DEPLOY
      deploy-branch: $BRANCH
      environments: >-
        [{\"name\":\"dev\",\"role_arn\":\"arn:aws:iam::111111111111:role/gha-deploy\",\"cluster\":\"dev-cluster\"},
         {\"name\":\"prod\",\"role_arn\":\"arn:aws:iam::222222222222:role/gha-deploy\",\"cluster\":\"prod-cluster\"}]"
  fi
  REG_BLOCK="      registry: $REGISTRY"
  [ "$REGISTRY" = ecr ] && REG_BLOCK="$REG_BLOCK
      ecr-role-arn: arn:aws:iam::111111111111:role/gha-ecr-push"
  write .github/workflows/pipeline.yml <<YAML
# Generated by github-action-templates/scripts/init-pipeline.sh: https://github.com/anuu1989/github-action-templates
name: pipeline

on:
  pull_request:
  push:
    branches: [$BRANCH]

permissions:
  contents: read

concurrency:
  group: \${{ github.workflow }}-\${{ github.ref }}
  cancel-in-progress: \${{ github.event_name == 'pull_request' }}

jobs:
  pipeline:
    uses: $TPL/pipeline-app.yml@$REF
    permissions:
$PERMS
    with:
      app-name: $REPO_NAME
$REG_BLOCK
${DEPLOY_BLOCK}
    secrets:
      SLACK_WEBHOOK_URL: \${{ secrets.SLACK_WEBHOOK_URL }}
YAML
  ;;
terraform)
  write .github/workflows/terraform.yml <<YAML
# Generated by github-action-templates/scripts/init-pipeline.sh: https://github.com/anuu1989/github-action-templates
name: terraform

on:
  pull_request:
    paths: ["$DIR/**", ".github/workflows/terraform.yml"]
  push:
    branches: [$BRANCH]
    paths: ["$DIR/**", ".github/workflows/terraform.yml"]

permissions:
  contents: read

concurrency:
  group: terraform-\${{ github.ref }}
  cancel-in-progress: false

jobs:
  terraform:
    uses: $TPL/pipeline-terraform.yml@$REF
    permissions:
      contents: read
      id-token: write
      pull-requests: write
    with:
      working-directory: $DIR
      apply-branch: $BRANCH
      # backends/<env>.hcl and envs/<env>.tfvars inside $DIR are picked up automatically
      environments: >-
        [{"name":"dev","role_arn":"arn:aws:iam::111111111111:role/gha-terraform"},
         {"name":"prod","role_arn":"arn:aws:iam::222222222222:role/gha-terraform"}]
    secrets:
      SLACK_WEBHOOK_URL: \${{ secrets.SLACK_WEBHOOK_URL }}
YAML
  ;;
security) ;;
*) echo "unknown --type $TYPE" >&2; exit 2 ;;
esac

write .github/workflows/security.yml <<YAML
# Generated by github-action-templates/scripts/init-pipeline.sh: https://github.com/anuu1989/github-action-templates
name: security

on:
  pull_request:
  push:
    branches: [$BRANCH]
  schedule:
    - cron: "30 3 * * 1"

permissions:
  contents: read

jobs:
  secrets:
    uses: $TPL/secret-scan.yml@$REF
  dependencies:
    uses: $TPL/trivy-scan.yml@$REF
    with:
      scan-type: fs
  workflow-policy:
    uses: $TPL/opa-conftest.yml@$REF
    with:
      policy-path: policies/opa/github-actions
      files: .github/workflows/
      namespace: github_actions
      run-policy-tests: false
YAML

if [ ! -e .github/dependabot.yml ]; then
  write .github/dependabot.yml <<'YAML'
version: 2
updates:
  - package-ecosystem: github-actions
    directory: /
    schedule:
      interval: weekly
YAML
fi

cat <<MSG

Next steps:
  1. Replace the placeholder account IDs / role ARNs (see docs/aws-oidc-setup.md in the template repo).
  2. Create GitHub Environments (Settings → Environments) for each environment; add reviewers to prod.
  3. Optional: add a SLACK_WEBHOOK_URL repository secret for notifications.
  4. git add .github && git commit -m "ci: add pipeline from github-action-templates" && git push
MSG
